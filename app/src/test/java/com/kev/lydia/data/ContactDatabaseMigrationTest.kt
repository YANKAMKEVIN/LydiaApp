package com.kev.lydia.data

import android.content.Context
import androidx.paging.PagingSource
import androidx.room.Room
import androidx.room.RoomDatabase
import com.kev.data.datasource.local.ContactDatabase
import com.kev.data.datasource.local.FavoriteEntity
import io.mockk.mockk
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.test.runTest
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder

/**
 * Upgrade of an installed database from version 3 (before favourites) to version 4.
 *
 * The version 3 file is written by hand with the schema Room generated for it; Room then opens it
 * with [ContactDatabase.MIGRATION_3_4] and validates the migrated schema against the entities (it
 * throws if they differ). No destructive fallback here: the cached contacts must be kept.
 */
class ContactDatabaseMigrationTest {

    @get:Rule
    val folder = TemporaryFolder()

    private var database: ContactDatabase? = null

    @After
    fun tearDown() {
        database?.close()
    }

    private fun createVersion3Database() {
        openJdbcConnection(folder.root.resolve(DB_NAME)).use { connection ->
            connection.createStatement().use { statement ->
                VERSION_3_SCHEMA.forEach { statement.execute(it) }
                statement.execute(
                    "INSERT INTO `ContactEntity` VALUES ('42', 'Jane Doe', 'female', 'jane@example.com', " +
                        "'0600000000', 'https://example.com/jane.jpg', 'Lyon', 'France', 30, '2020-01-01', 'jane')"
                )
                statement.execute("INSERT INTO `RemoteKeys` VALUES ('42', NULL, 2)")
                statement.execute("PRAGMA user_version = 3")
            }
        }
    }

    private fun openWithMigrations(): ContactDatabase =
        Room.databaseBuilder(mockk<Context>(relaxed = true), ContactDatabase::class.java, DB_NAME)
            .openHelperFactory(JdbcSQLiteOpenHelperFactory(folder.root))
            .setJournalMode(RoomDatabase.JournalMode.TRUNCATE)
            .addMigrations(ContactDatabase.MIGRATION_3_4)
            .allowMainThreadQueries()
            .build()
            .also { database = it }

    @Test
    fun `migrating from 3 to 4 keeps the cached contacts and adds the favourites`() = runTest {
        createVersion3Database()

        val db = openWithMigrations()
        // Room opens the file lazily: the first query runs the migration and validates the schema.
        assertTrue(db.favoriteDao.observeIds().first().isEmpty())

        val contacts = (db.contactDao.pagingSource().load(
            PagingSource.LoadParams.Refresh(key = null, loadSize = 20, placeholdersEnabled = false)
        ) as PagingSource.LoadResult.Page).data
        assertEquals(listOf("Jane Doe"), contacts.map { it.fullName })
        assertEquals(2, db.remoteKeysDao.remoteKeysById("42")?.nextKey)

        db.favoriteDao.add(FavoriteEntity("42"))
        assertEquals(listOf("42"), db.favoriteDao.observeIds().first())
        assertEquals(4, db.openHelper.writableDatabase.version)
    }

    private companion object {
        const val DB_NAME = "contacts.db"

        /** Schema of version 3, as generated by Room in ContactDatabase_Impl.createAllTables. */
        val VERSION_3_SCHEMA = listOf(
            "CREATE TABLE IF NOT EXISTS `ContactEntity` (`id` TEXT NOT NULL, `fullName` TEXT NOT NULL, " +
                "`gender` TEXT NOT NULL, `email` TEXT NOT NULL, `phone` TEXT NOT NULL, `avatarUrl` TEXT NOT NULL, " +
                "`city` TEXT NOT NULL, `country` TEXT NOT NULL, `age` INTEGER NOT NULL, " +
                "`registeredDate` TEXT NOT NULL, `username` TEXT NOT NULL, PRIMARY KEY(`id`))",
            "CREATE TABLE IF NOT EXISTS `RemoteKeys` (`repoId` TEXT NOT NULL, `prevKey` INTEGER, " +
                "`nextKey` INTEGER, PRIMARY KEY(`repoId`))",
            "CREATE TABLE IF NOT EXISTS room_master_table (id INTEGER PRIMARY KEY,identity_hash TEXT)",
            "INSERT OR REPLACE INTO room_master_table (id,identity_hash) VALUES(42, 'bc232475dcef33036603f68da837181c')",
        )
    }
}
